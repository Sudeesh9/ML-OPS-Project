import io
import pandas as pd
from typing import Optional
from fastapi import APIRouter, Response, UploadFile, File, Form, HTTPException
import evidently

from app.services.evidently_service import evidently_service

router = APIRouter(prefix="/evidently", tags=["Evidently AI Monitoring"])

@router.get("/status")
def get_evidently_status():
    """
    Returns Evidently AI monitoring engine status and version.
    """
    return {
        "status": "active",
        "service": "Evidently AI Drift & Data Quality",
        "version": evidently.__version__,
        "reference_dataset": "data/reviews.csv",
        "available_presets": [
            "DataDriftPreset",
            "DataSummaryPreset"
        ],
        "cached_report_ready": evidently_service._cached_html is not None,
        "last_generated": evidently_service._last_generated
    }

@router.get("/drift-summary")
def get_drift_summary():
    """
    Returns structured JSON drift summary metrics for dashboard visualization.
    """
    try:
        return evidently_service.get_summary()
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"Failed to generate drift summary: {str(e)}")

@router.get("/drift-report")
def get_drift_report_html():
    """
    Serves the standalone interactive HTML report generated by Evidently AI.
    Can be viewed directly in a browser tab or embedded in an iframe.
    """
    try:
        html_content = evidently_service.get_cached_html()
        return Response(content=html_content, media_type="text/html")
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"Failed to generate drift report HTML: {str(e)}")

@router.post("/run-drift")
async def run_custom_drift(
    file: Optional[UploadFile] = File(None),
    review_column: str = Form("review_text")
):
    """
    Triggers an on-demand Evidently AI drift report against either the reference sample
    or an uploaded custom dataset file (CSV/XLSX).
    """
    current_df = None
    if file:
        filename = file.filename or "uploaded.csv"
        contents = await file.read()
        try:
            if filename.endswith(".csv"):
                current_df = pd.read_csv(io.BytesIO(contents))
            elif filename.endswith((".xlsx", ".xls")):
                current_df = pd.read_excel(io.BytesIO(contents))
            else:
                raise HTTPException(status_code=400, detail="Only .csv and .xlsx files are supported.")
        except Exception as e:
            raise HTTPException(status_code=400, detail=f"Error reading file: {str(e)}")

    try:
        summary = evidently_service.run_drift_analysis(current_df=current_df, review_col=review_column)
        return summary
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"Drift computation failed: {str(e)}")
